    def _save_product(product_id):
        code = request.form.get("code", "").strip()
        name = request.form.get("name", "").strip()
        if not code or not name:
            flash(translations.tr("err.missing"), "danger")
            return redirect(request.url)
        try:
            price = float(request.form.get("base_price", "0") or 0)
        except ValueError:
            flash(translations.tr("err.invalid_price"), "danger")
            return redirect(request.url)

        # Variants: collected from repeated form fields. Each row submits a
        # v_color/v_size select plus optional v_color_new/v_size_new text
        # inputs (revealed when "add new" was chosen). Resolve server-side —
        # never trust the literal "__new__" sentinel to reach the database.
        colors = request.form.getlist("v_color")
        colors_new = request.form.getlist("v_color_new")
        sizes = request.form.getlist("v_size")
        sizes_new = request.form.getlist("v_size_new")

        def _resolve(values, news, i):
            v = values[i].strip() if i < len(values) else ""
            if v == "__new__":
                v = news[i].strip() if i < len(news) else ""
            return v

        variants = []
        for i in range(max(len(colors), len(sizes))):
            c = _resolve(colors, colors_new, i)
            s = _resolve(sizes, sizes_new, i)
            if c or s:
                variants.append((c, s))
        # Deduplicate preserving order.
        seen = set()
        unique = []
        for c, s in variants:
            if (c, s) not in seen:
                seen.add((c, s))
                unique.append((c, s))

        # Optional image upload.
        image_bytes, image_ext, keep = None, None, True
        upload = request.files.get("image")
        remove = request.form.get("remove_image") == "1"
        if upload and upload.filename:
            data = upload.read()
            if data:
                image_bytes, image_ext = _optimise_image(data)
        elif remove:
            keep = False

        if product_id is None:
            new_id = repository.create_product(
                code, name, price, image_bytes, image_ext, unique
            )
            flash(f"Product #{new_id} created.", "success")
        else:
            repository.update_product(
                product_id, code, name, price, image_bytes, image_ext, unique, keep
            )
            # Invalidate the cached thumbnail so the new image shows up.
            _thumb_cache.pop(product_id, None)
            flash("Product updated.", "success")
        return redirect(url_for("inventory"))

    @app.route("/inventory/<int:product_id>")
    @login_required
    def product_detail(product_id: int):
        product = repository.get_product(product_id)
        if not product:
            flash("Product not found.", "danger")
            return redirect(url_for("inventory"))
        variants = repository.list_variants(product_id)
        stock_in = repository.list_stock_in(product_id)
        stock_out = repository.list_stock_out(product_id)
        # Distinct colors / sizes for the dropdown selectors.
        colors = sorted({v["color"] for v in variants})
        sizes = sorted({v["size"] for v in variants})
        # Combined, newest-first movement history for the History tab.
        history = []
        for r in stock_in:
            history.append({
                "type": "IN", "date": _iso(r["date"]),
                "color": r["color"], "size": r["size"],
                "quantity": r["quantity"],
                "info": f"cost {_fmt(r['unit_cost'])}  {r['note']}".strip(),
            })
        for r in stock_out:
            history.append({
                "type": "OUT", "date": _iso(r["date"]),
                "color": r["color"], "size": r["size"],
                "quantity": r["quantity"],
                "info": f"{r['customer_name']}  {r['note']}".strip(),
            })
        history.sort(key=lambda x: (str(x["date"]), x["type"]), reverse=True)
        return render_template(
            "inventory/detail.html",
            product=product,
            stock_total=repository.product_stock_total(product_id),
            variants=variants,
            stock_in=stock_in,
            stock_out=stock_out,
            colors=colors,
            sizes=sizes,
            history=history,
        )

